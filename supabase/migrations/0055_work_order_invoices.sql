-- IRep Property Management: itemized invoices for work orders.
--   * work_order_lines: the invoice's line items (description, quantity, unit price, HST or not).
--     Saving an invoice sets the work order's actual cost to the total (with HST) and the
--     contractor's pay to the subtotal before HST (IRep holds the HST back).
--   * maintenance_requests.invoice_no: invoice number (shown as WO-00042); invoice_notes.
--   * work_order_invoice(id): the invoice for staff, or for the landlord who owns the property.
--   * owner_letter_data now includes each work order's id, so letters can link to its invoice.
--   * Existing priced work orders get one line each from what's already recorded.
-- Run AFTER 0054. Safe to re-run.

create table if not exists public.work_order_lines (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.maintenance_requests (id) on delete cascade,
  sort integer not null default 0,
  description text not null,
  quantity numeric(10, 2) not null default 1 check (quantity > 0),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  taxable boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists work_order_lines_request_idx on public.work_order_lines (request_id, sort);

alter table public.work_order_lines enable row level security;
drop policy if exists "work_order_lines: staff all" on public.work_order_lines;
create policy "work_order_lines: staff all" on public.work_order_lines
  for all using (public.is_staff()) with check (public.is_staff());
revoke all on public.work_order_lines from anon;

alter table public.maintenance_requests add column if not exists invoice_no bigint generated by default as identity;
alter table public.maintenance_requests add column if not exists invoice_notes text;

create or replace function public.work_order_invoice(p_request_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  r record;
  hst numeric := coalesce((select amount from public.service_rates where key = 'hst'), 13);
  lines jsonb;
  sub numeric;
  tax numeric;
begin
  select mr.*, u.label as unit_label, pr.id as property_id, pr.address, pr.city, pr.postal_code, pr.owner_id,
         o.name as owner_name, o.mailing_address as owner_address
    into r
    from public.maintenance_requests mr
    join public.units u on u.id = mr.unit_id
    join public.properties pr on pr.id = u.property_id
    left join public.owners o on o.id = pr.owner_id
   where mr.id = p_request_id;
  if not found then return null; end if;
  if not (public.is_staff() or auth.uid() is null or public.is_owner_account(r.owner_id)) then
    raise exception 'Not allowed';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('description', l.description, 'quantity', l.quantity,
                    'unit_price', l.unit_price, 'taxable', l.taxable,
                    'amount', round(l.quantity * l.unit_price, 2)) order by l.sort, l.created_at), '[]'::jsonb),
         coalesce(sum(round(l.quantity * l.unit_price, 2)), 0),
         coalesce(round(sum(case when l.taxable then round(l.quantity * l.unit_price, 2) else 0 end) * hst / 100, 2), 0)
    into lines, sub, tax
    from public.work_order_lines l where l.request_id = p_request_id;

  return jsonb_build_object(
    'id', r.id,
    'invoice_no', r.invoice_no,
    'title', r.title,
    'description', r.description,
    'category', r.category,
    'status', r.status,
    'charge_to', r.charge_to,
    'unit', r.unit_label,
    'address', r.address, 'city', r.city, 'postal_code', r.postal_code,
    'owner_name', r.owner_name, 'owner_address', r.owner_address,
    'reported_on', (r.created_at at time zone 'America/Toronto')::date,
    'completed_on', (r.completed_at at time zone 'America/Toronto')::date,
    'notes', r.invoice_notes,
    'hst_percent', hst,
    'lines', lines,
    'subtotal', sub,
    'hst', tax,
    'total', sub + tax,
    'actual_cost', r.actual_cost);
end;
$$;
revoke execute on function public.work_order_invoice(uuid) from public, anon;
grant execute on function public.work_order_invoice(uuid) to authenticated, service_role;

-- Letters: include the work order id so the letter can link to its invoice.
do $$
declare d text := pg_get_functiondef('public.owner_letter_data'::regproc);
begin
  if position('''id'', mr.id' in d) = 0 then
    execute replace(d, '''charge_to'', mr.charge_to)', '''charge_to'', mr.charge_to, ''id'', mr.id)');
  end if;
end $$;

-- One line for each existing priced work order that has no lines yet.
insert into public.work_order_lines (request_id, description, quantity, unit_price, taxable)
select mr.id, mr.title, 1,
       coalesce(mr.partner_pay, case when mr.charge_to = 'irep' then mr.actual_cost else round(mr.actual_cost / 1.13, 2) end),
       mr.charge_to <> 'irep' and (mr.partner_pay is null or mr.actual_cost > mr.partner_pay)
  from public.maintenance_requests mr
 where mr.status = 'completed' and coalesce(mr.actual_cost, 0) > 0
   and not exists (select 1 from public.work_order_lines l where l.request_id = mr.id);
