-- 0071: general invoices (leasing fees for leasing-only clients, and anything else IRep bills).
--   * invoices / invoice_lines. Numbers show as INV-00001.
--   * Drafts can be edited or deleted. Once sent, the bill-to, lines and HST are fixed:
--     to change a sent invoice, void it and make a new one.
--   * Leasing-fee lines on sent or paid invoices count as leasing fees in the month issued
--     (leasing_fee_lines, so the commission split and the fiscal year include them).
--   * invoice_doc(id): one invoice with totals, for staff or the landlord billed (not drafts).
--   * owner_invoices(): the signed-in landlord's invoices.
-- Run AFTER 0070. Safe to re-run.

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_no bigint generated by default as identity unique,
  status text not null default 'draft' check (status in ('draft', 'sent', 'paid', 'void')),
  owner_id uuid references public.owners (id) on delete set null,
  property_id uuid references public.properties (id) on delete set null,
  bill_to_name text not null check (length(trim(bill_to_name)) > 0),
  bill_to_email text,
  bill_to_address text,
  title text not null default 'Invoice',
  description text,
  issue_date date not null default ((now() at time zone 'America/Toronto')::date),
  due_date date,
  hst_percent numeric(5, 2) not null default 13 check (hst_percent >= 0 and hst_percent <= 25),
  notes text,
  staff_note text,
  sent_at timestamptz,
  sent_to text,
  paid_on date,
  paid_method text check (paid_method is null or paid_method in ('etransfer', 'cheque', 'cash', 'direct_deposit', 'card', 'deducted', 'other')),
  paid_reference text,
  void_reason text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'paid' or paid_on is not null),
  check (due_date is null or due_date >= issue_date)
);
create index if not exists invoices_owner_idx on public.invoices (owner_id, issue_date desc);
create index if not exists invoices_status_idx on public.invoices (status, issue_date desc);

create table if not exists public.invoice_lines (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.invoices (id) on delete cascade,
  sort integer not null default 0,
  category text not null default 'service' check (category in ('leasing_fee', 'service', 'other')),
  description text not null check (length(trim(description)) > 0),
  quantity numeric(10, 2) not null default 1 check (quantity > 0),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  taxable boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists invoice_lines_invoice_idx on public.invoice_lines (invoice_id, sort);

alter table public.invoices enable row level security;
alter table public.invoice_lines enable row level security;
drop policy if exists "invoices: staff all" on public.invoices;
create policy "invoices: staff all" on public.invoices for all using (public.is_staff()) with check (public.is_staff());
drop policy if exists "invoice_lines: staff all" on public.invoice_lines;
create policy "invoice_lines: staff all" on public.invoice_lines for all using (public.is_staff()) with check (public.is_staff());
revoke all on public.invoices from anon;
revoke all on public.invoice_lines from anon;

-- Once an invoice has gone out, what it says can't change.
create or replace function public.invoices_rules()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception 'Only a draft invoice can be deleted. Void it instead.';
    end if;
    return old;
  end if;
  new.updated_at := now();
  if old.status <> 'draft' and (
       new.owner_id is distinct from old.owner_id or new.property_id is distinct from old.property_id
    or new.bill_to_name is distinct from old.bill_to_name or new.bill_to_address is distinct from old.bill_to_address
    or new.title is distinct from old.title or new.description is distinct from old.description
    or new.issue_date is distinct from old.issue_date or new.due_date is distinct from old.due_date
    or new.hst_percent is distinct from old.hst_percent or new.notes is distinct from old.notes) then
    raise exception 'This invoice has been sent, so its details can''t change. Void it and make a new one.';
  end if;
  if old.status = 'void' and new.status <> 'void' then
    raise exception 'A void invoice can''t be reopened. Make a new one.';
  end if;
  if new.status = 'draft' and old.status <> 'draft' then
    raise exception 'A sent invoice can''t go back to draft. Void it and make a new one.';
  end if;
  if new.status = 'sent' and old.status = 'draft' then
    new.sent_at := coalesce(new.sent_at, now());
  end if;
  if new.status <> 'paid' then
    new.paid_on := null; new.paid_method := null; new.paid_reference := null;
  end if;
  return new;
end;
$$;
drop trigger if exists invoices_rules on public.invoices;
create trigger invoices_rules before update or delete on public.invoices
  for each row execute function public.invoices_rules();

create or replace function public.invoice_lines_rules()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  st text;
begin
  select status into st from public.invoices where id = coalesce(new.invoice_id, old.invoice_id);
  if st is not null and st <> 'draft' then
    raise exception 'This invoice has been sent, so its lines can''t change. Void it and make a new one.';
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists invoice_lines_rules on public.invoice_lines;
create trigger invoice_lines_rules before insert or update or delete on public.invoice_lines
  for each row execute function public.invoice_lines_rules();

-- Totals: HST on the taxable lines, rounded once per invoice.
create or replace view public.invoice_totals with (security_invoker = true) as
select i.id as invoice_id,
       coalesce(sum(round(l.quantity * l.unit_price, 2)), 0)::numeric(12, 2) as subtotal,
       round(coalesce(sum(round(l.quantity * l.unit_price, 2)) filter (where l.taxable), 0) * i.hst_percent / 100, 2)::numeric(12, 2) as hst,
       (coalesce(sum(round(l.quantity * l.unit_price, 2)), 0)
        + round(coalesce(sum(round(l.quantity * l.unit_price, 2)) filter (where l.taxable), 0) * i.hst_percent / 100, 2))::numeric(12, 2) as total
  from public.invoices i
  left join public.invoice_lines l on l.invoice_id = i.id
 group by i.id, i.hst_percent;

-- One invoice, for staff or (once sent) the landlord it bills.
create or replace function public.invoice_doc(p_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select to_jsonb(i) - 'staff_note' - 'created_by'
         || jsonb_build_object(
              'subtotal', t.subtotal, 'hst', t.hst, 'total', t.total,
              'property_address', concat_ws(', ', p.address, nullif(p.city, '')),
              'lines', coalesce((select jsonb_agg(jsonb_build_object(
                          'id', l.id, 'category', l.category, 'description', l.description, 'quantity', l.quantity,
                          'unit_price', l.unit_price, 'taxable', l.taxable, 'amount', round(l.quantity * l.unit_price, 2))
                          order by l.sort, l.created_at)
                        from public.invoice_lines l where l.invoice_id = i.id), '[]'::jsonb))
         || case when public.is_staff() or auth.uid() is null then jsonb_build_object('staff_note', i.staff_note) else '{}'::jsonb end
    from public.invoices i
    join public.invoice_totals t on t.invoice_id = i.id
    left join public.properties p on p.id = i.property_id
   where i.id = p_id
     and (public.is_staff() or auth.uid() is null
          or (i.status in ('sent', 'paid') and i.owner_id is not null and public.is_owner_account(i.owner_id)));
$$;
revoke execute on function public.invoice_doc(uuid) from public, anon;
grant execute on function public.invoice_doc(uuid) to authenticated, service_role;

create or replace function public.owner_invoices()
returns table (id uuid, invoice_no bigint, status text, title text, issue_date date, due_date date,
               address text, total numeric, paid_on date)
language sql
stable
security definer
set search_path = public
as $$
  select i.id, i.invoice_no, i.status, i.title, i.issue_date, i.due_date, concat_ws(', ', p.address, nullif(p.city, '')), t.total, i.paid_on
    from public.invoices i
    join public.invoice_totals t on t.invoice_id = i.id
    left join public.properties p on p.id = i.property_id
   where i.status in ('sent', 'paid') and i.owner_id is not null and public.is_owner_account(i.owner_id)
   order by i.issue_date desc, i.invoice_no desc;
$$;
revoke execute on function public.owner_invoices() from public, anon;
grant execute on function public.owner_invoices() to authenticated;

-- Leasing fees billed by invoice count with the ones taken from landlord statements.
-- (New column invoice_line_id at the end; statement rows leave it null, invoice rows leave statement_item_id null.)
create or replace view public.leasing_fee_lines as
 with hst as (
   select coalesce((select service_rates.amount from service_rates where service_rates.key = 'hst'), 13::numeric) as pct
 )
 select i.id as statement_item_id,
    i.property_id,
    i.period,
    i.description,
    i.tenancy_id,
    (- i.amount) as fee_incl_hst,
    round((- i.amount) * 100::numeric / (100::numeric + hst.pct), 2) as fee,
    (- i.amount) - round((- i.amount) * 100::numeric / (100::numeric + hst.pct), 2) as hst,
    null::uuid as invoice_line_id
   from statement_items i cross join hst
  where i.kind = 'leasing_fee'
 union all
 select null::uuid,
    v.property_id,
    date_trunc('month', v.issue_date)::date,
    'Invoice INV-' || lpad(v.invoice_no::text, 5, '0') || ': ' || l.description,
    null::uuid,
    round(l.quantity * l.unit_price, 2) + case when l.taxable then round(round(l.quantity * l.unit_price, 2) * v.hst_percent / 100, 2) else 0 end,
    round(l.quantity * l.unit_price, 2),
    case when l.taxable then round(round(l.quantity * l.unit_price, 2) * v.hst_percent / 100, 2) else 0 end,
    l.id
   from invoice_lines l
   join invoices v on v.id = l.invoice_id
  where l.category = 'leasing_fee' and v.status in ('sent', 'paid') and v.property_id is not null;

create or replace view public.leasing_fee_splits as
 select l.statement_item_id,
    l.property_id,
    l.period,
    l.description,
    l.tenancy_id,
    l.fee_incl_hst,
    l.fee,
    l.hst,
    p.address,
    round(l.fee / 4::numeric, 2) as rishi_commission,
    round(l.fee / 4::numeric, 2) as chuck_commission,
    round(l.fee / 4::numeric, 2) as rishi_loan,
    l.fee - 3::numeric * round(l.fee / 4::numeric, 2) as chuck_loan,
    l.invoice_line_id
   from leasing_fee_lines l
   join properties p on p.id = l.property_id;
